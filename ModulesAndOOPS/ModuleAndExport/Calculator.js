/*export → share a class from a module
import → use the class in another module
extends → inherit from the imported class */

export function add(a, b) {
  return a + b;
}

export function sub(a, b) {
  return a - b;
}

export function mul(a, b) {
  return a * b;
}

export function div(a, b) {
  return a / b;
}
