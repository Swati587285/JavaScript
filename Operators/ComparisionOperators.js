let x=10;
let y=10;

console.log(x==y);      //  Equal value - true
console.log(x!=y);      //  Not Equal value - false
console.log(x===y);     //  Equal value and type - true
console.log(x!==y);     //  Not Equal value or type - false
console.log(x>y);       //  Greater than - false
console.log(x<y);       //  Less than - false
console.log(x>=y);      //  Greater than or equal - true
console.log(x<=y);      //  Less than or equal - true